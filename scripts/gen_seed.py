import json, os
here=os.path.dirname(os.path.abspath(__file__))
T=json.load(open(os.path.join(here,'../packages/templates/templates.json')))
q=lambda s: "NULL" if s is None else "'"+str(s).replace("'","''")+"'"
out=["-- Reference/config seed (generated by scripts/gen_seed.py). Contains NO market figures or fake results."]
for t in T:
    out.append(f"INSERT OR IGNORE INTO study_templates (id,sector,name_ar,name_en,icon,image,is_active,current_version,sort_order) VALUES ({q(t['id'])},{q(t['sector'])},{q(t['name_ar'])},{q(t['name_en'])},{q(t['icon'])},{q(t['image'])},1,1,{t['sort_order']});")
    out.append(f"INSERT OR IGNORE INTO study_template_versions (template_id,version,definition_json,created_by) VALUES ({q(t['id'])},1,{q(json.dumps(t['definition'],ensure_ascii=False))},'system');")
open(os.path.join(here,'../migrations/0002_seed_templates.sql'),'w').write("\n".join(out)+"\n")
print("ok", len(T))
